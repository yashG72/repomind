import pytest

from repomind.core.models import SkipReason
from repomind.ingestion.file_filter import DefaultFileFilter, normalize_archive_path

FILTER = DefaultFileFilter(max_file_size_bytes=1_000)


@pytest.mark.parametrize(
    ("path", "language"),
    [
        ("src/app.py", "python"),
        ("web/App.TSX", "typescript"),
        ("cmd/main.go", "go"),
        ("Dockerfile", "dockerfile"),
        ("docker/Dockerfile.prod", "dockerfile"),
        ("Makefile", "makefile"),
        ("docs/guide.md", "markdown"),
    ],
)
def test_supported_files_pass_and_get_a_language(path: str, language: str) -> None:
    assert FILTER.check_path(path, 10) is None
    assert FILTER.language_for(path) == language


@pytest.mark.parametrize(
    ("path", "reason"),
    [
        ("node_modules/react/index.js", SkipReason.EXCLUDED_DIRECTORY),
        ("frontend/node_modules/x.js", SkipReason.EXCLUDED_DIRECTORY),
        ("vendor/lib.go", SkipReason.EXCLUDED_DIRECTORY),
        (".venv/lib/site.py", SkipReason.EXCLUDED_DIRECTORY),
        ("dist/app.js", SkipReason.EXCLUDED_DIRECTORY),
        ("pkg/__pycache__/m.py", SkipReason.EXCLUDED_DIRECTORY),
        (".git/config", SkipReason.EXCLUDED_DIRECTORY),
        (".env", SkipReason.SECRET_FILE),
        ("config/.env.production", SkipReason.SECRET_FILE),
        ("deploy/server.pem", SkipReason.SECRET_FILE),
        ("keys/id_rsa", SkipReason.SECRET_FILE),
        ("gcp/credentials.json", SkipReason.SECRET_FILE),
        ("package-lock.json", SkipReason.LOCK_FILE),
        ("api/poetry.lock", SkipReason.LOCK_FILE),
        ("go.sum", SkipReason.LOCK_FILE),
        ("static/app.min.js", SkipReason.GENERATED),
        ("static/app.js.map", SkipReason.GENERATED),
        ("proto/user_pb2.py", SkipReason.GENERATED),
        ("assets/logo.png", SkipReason.UNSUPPORTED_TYPE),
        ("bin/tool.exe", SkipReason.UNSUPPORTED_TYPE),
        ("data/archive.zip", SkipReason.UNSUPPORTED_TYPE),
        (".env.example", SkipReason.UNSUPPORTED_TYPE),
        ("big.py", None),  # size checked separately below
        ("../etc/passwd.py", SkipReason.UNSAFE_PATH),
        ("/abs/path.py", SkipReason.UNSAFE_PATH),
    ],
)
def test_path_rules(path: str, reason: SkipReason | None) -> None:
    assert FILTER.check_path(path, 10) == reason


def test_size_limits() -> None:
    assert FILTER.check_path("big.py", 1_001) == SkipReason.TOO_LARGE
    assert FILTER.check_path("big.py", 1_000) is None
    assert FILTER.check_path("empty.py", 0) == SkipReason.EMPTY


@pytest.mark.parametrize(
    ("data", "reason"),
    [
        (b"print('hi')\n", None),
        (b"\xef\xbb\xbfprint('bom')\n", None),
        (b"   \n\n", SkipReason.EMPTY),
        (b"\x89PNG\r\n\x1a\n\x00\x00binary", SkipReason.BINARY),
        (b"caf\xe9 latin-1", SkipReason.NOT_UTF8),
        (
            b"-----BEGIN RSA PRIVATE KEY-----\nMIIE\n-----END RSA PRIVATE KEY-----\n",
            SkipReason.SECRET_FILE,
        ),
        (b"-----BEGIN OPENSSH PRIVATE KEY-----\nabc\n", SkipReason.SECRET_FILE),
        (b"// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n", SkipReason.GENERATED),
        (b"# @generated by tool\nx = 1\n", SkipReason.GENERATED),
        (b"var a=1;" * 1_000, SkipReason.MINIFIED),
    ],
)
def test_content_rules(data: bytes, reason: SkipReason | None) -> None:
    assert FILTER.check_content("file.py", data) == reason


@pytest.mark.parametrize(
    ("raw", "expected"),
    [
        ("src/app.py", "src/app.py"),
        ("./src//app.py", "src/app.py"),
        ("../secret", None),
        ("src/../../secret", None),
        ("/etc/passwd", None),
        ("src\\..\\win.py", None),
        ("bad\x00name.py", None),
        ("new\nline.py", None),
        ("", None),
        (".", None),
        ("a/" * 600, None),  # too long
    ],
)
def test_normalize_archive_path(raw: str, expected: str | None) -> None:
    assert normalize_archive_path(raw) == expected
